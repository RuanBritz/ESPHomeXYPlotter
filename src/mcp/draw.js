// Turn simple geometry into plotter G-code.

/**
 * Convert polylines (in mm) to G-code: travel with the pen up, draw with it down.
 * A polyline with one point makes a dot.
 * @param {Array<Array<[number, number]>>} polylines
 * @param {{ penUp?: string, penDown?: string, feed?: number, closed?: boolean,
 *           penDelayMs?: number, returnHome?: boolean }} [options]
 * @returns {string}
 */
export function polylinesToGcode(polylines, options = {}) {
  const {
    penUp = 'M5',
    penDown = 'M3 S1000',
    feed = 3000,
    closed = false,
    penDelayMs = 0,
    returnHome = false,
  } = options;

  if (!Array.isArray(polylines) || !polylines.length) throw new Error('polylines must be a non-empty array');
  if (!(feed > 0)) throw new Error('feed must be a positive number');

  const out = ['; generated by the xy-plotter MCP server', 'G21', 'G90', penUp];
  const dwell = penDelayMs > 0 ? `G4 P${fmt(penDelayMs / 1000)}` : null;
  let points = 0;

  polylines.forEach((line, n) => {
    if (!Array.isArray(line) || !line.length) throw new Error(`polyline ${n} is empty`);
    line.forEach((p, i) => {
      if (!Array.isArray(p) || p.length !== 2 || !p.every(Number.isFinite)) {
        throw new Error(`polyline ${n}, point ${i} must be [x, y] numbers`);
      }
    });

    const [x0, y0] = line[0];
    out.push(`G0 X${fmt(x0)} Y${fmt(y0)}`, penDown);
    if (dwell) out.push(dwell);
    for (let i = 1; i < line.length; i++) {
      out.push(`G1 X${fmt(line[i][0])} Y${fmt(line[i][1])}${i === 1 ? ` F${fmt(feed)}` : ''}`);
    }
    if (closed && line.length > 2) out.push(`G1 X${fmt(x0)} Y${fmt(y0)}`);
    out.push(penUp);
    if (dwell) out.push(dwell);
    points += line.length;
  });

  if (returnHome) out.push('G0 X0 Y0');
  out.push(`; ${polylines.length} polylines, ${points} points`);
  return out.join('\n') + '\n';
}

function fmt(n) {
  return String(Math.round(n * 1000) / 1000);
}
