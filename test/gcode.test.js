import test from 'node:test';
import assert from 'node:assert/strict';
import { analyze, cleanLine, splitLines, stateBefore } from '../shared/gcode.js';

test('cleanLine strips comments, line numbers, checksums and normalises', () => {
  assert.equal(cleanLine('g1  x10 y20 ; move'), 'G1 X10 Y20');
  assert.equal(cleanLine('N120 G0 X1*57'), 'G0 X1');
  assert.equal(cleanLine('(only a comment)'), '');
  assert.equal(cleanLine('; generated by inkscape'), '');
  assert.equal(cleanLine('G1 (inline) X5'), 'G1 X5');
  assert.equal(cleanLine('%'), '');
  assert.equal(cleanLine('  \r'), '');
  assert.equal(cleanLine('$$'), '$$');
});

test('splitLines handles CRLF and trailing newline', () => {
  assert.deepEqual(splitLines('a\r\nb\nc\n'), ['a', 'b', 'c']);
});

test('analyze computes drawn bounds with relative moves and inches', () => {
  const lines = splitLines(['G21 G90', 'M5', 'G0 X10 Y10', 'M3 S1000', 'G1 X20', 'G91', 'G1 Y5', 'M5', 'G90 G0 X100 Y100'].join('\n'));
  const { bounds, segments, commandCount } = analyze(lines);
  assert.deepEqual(bounds, { minX: 10, minY: 10, maxX: 20, maxY: 15 });
  assert.equal(commandCount, 9);
  // 4 segments: travel, draw, draw, travel
  assert.equal(segments.length / 6, 4);
  assert.equal(segments[4], 0);
  assert.equal(segments[10], 1);

  const inch = analyze(['G20', 'M3', 'G1 X1 Y1']);
  assert.ok(Math.abs(inch.bounds.maxX - 25.4) < 1e-4);
});

test('analyze returns null bounds for files without moves', () => {
  assert.equal(analyze(['; nothing', 'M5']).bounds, null);
});

test('arcs are interpolated for the preview', () => {
  const { segments, bounds } = analyze(['G0 X0 Y0', 'M3', 'G2 X20 Y0 I10 J0']);
  assert.ok(segments.length / 6 > 10);
  assert.ok(bounds.maxY > 9.9); // clockwise from (0,0) to (20,0) around (10,0) goes through y=+10
});

test('stateBefore + preamble restore position, pen and modes', () => {
  const lines = ['G21', 'G90', 'F1500', 'M3 S1000', 'G1 X10 Y5', 'G91', 'G1 X1'];
  const pre = stateBefore(lines, 6).preamble();
  assert.deepEqual(pre, ['M5', 'G21', 'G90', 'G0 X10 Y5', 'M3 S1000', 'G91', 'F1500', 'G1']);
  const start = stateBefore(lines, 0).preamble();
  assert.deepEqual(start, ['M5', 'G21', 'G90', 'G0 X0 Y0', 'G0']);
});
